let activeCategory = "Todos";
let currentArticleIndex = 0;

const categories = [
    "Todos",
    ...new Set(articles.map(article => article.category))
];

function createFilters() {

    filters.innerHTML = "";

    categories.forEach(category => {

        const button = document.createElement("button");

        button.type = "button";
        button.className = "filter-button";

        if (category === activeCategory) {
            button.classList.add("active");
        }

        button.textContent = category;

        button.addEventListener("click", () => {

            activeCategory = category;

            createFilters();
            renderArticles();

        });

        filters.appendChild(button);

    });
}

function renderArticles() {

    const query = searchInput.value
        .trim()
        .toLowerCase();

    const visibleArticles = articles.filter(article => {

        const matchesCategory =
            activeCategory === "Todos" ||
            article.category === activeCategory;

        const searchableText = [
            article.title,
            article.intro,
            article.category,
            ...article.sections.flat()
        ]
            .join(" ")
            .toLowerCase();

        const matchesSearch =
            !query ||
            searchableText.includes(query);

        return matchesCategory && matchesSearch;

    });

    if (!visibleArticles.length) {

        grid.innerHTML = `
            <p style="color:#777">
                No encontramos una entrada con esa bÃºsqueda.
            </p>
        `;

        return;
    }

    grid.innerHTML = visibleArticles.map(article => {

        return `
            <article
                class="article-card"
                data-id="${article.id}"
                tabindex="0"
                role="button"
                aria-label="Leer ${article.title}"
            >

                <div class="card-top">

                    <span>
                        ${article.category}
                    </span>

                    <span class="card-icon">
                        ${article.icon}
                    </span>

                </div>

                <h4>
                    ${article.title}
                </h4>

                <p>
                    ${article.intro}
                </p>

                <span class="read-link">
                    LEER LA ENTRADA â†’
                </span>

            </article>
        `;

    }).join("");

    grid.querySelectorAll(".article-card").forEach(card => {

        const open = () => {
            openReader(Number(card.dataset.id));
        };

        card.addEventListener("click", open);

        card.addEventListener("keydown", event => {

            if (event.key === "Enter" || event.key === " ") {

                event.preventDefault();
                open();

            }

        });

    });
}

function openReader(id) {

    currentArticleIndex =
        articles.findIndex(article => article.id === id);

    const article = articles[currentArticleIndex];

    if (!article) {
        return;
    }

    readerCategory.textContent = article.category;

    readerNumber.textContent =
        `${String(currentArticleIndex + 1).padStart(2, "0")} / ${articles.length}`;

    readerTitle.textContent = article.title;
    readerIntro.textContent = article.intro;

    readerBody.innerHTML = article.sections
        .map(([heading, paragraph]) => {

            if (!heading) {
                return `<p>${paragraph}</p>`;
            }

            return `
                <h3>${heading}</h3>
                <p>${paragraph}</p>
            `;

        })
        .join("");

    reader.classList.add("open");
    reader.setAttribute("aria-hidden", "false");

    document.body.classList.add("reader-open");
}

function closeReader() {

    reader.classList.remove("open");
    reader.setAttribute("aria-hidden", "true");

    document.body.classList.remove("reader-open");
}

function openNextArticle() {

    const nextIndex =
        (currentArticleIndex + 1) % articles.length;

    openReader(articles[nextIndex].id);
}

